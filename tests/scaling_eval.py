#! /usr/bin/env python3
# Kernel scaling evaluation. Answers the question that motivated the
# kernel : does the numpy-thin path unlock node-level parallelism that
# the pyEDM path could not use ( T4 showed pyEDM was GIL-bound ) ?
#
# Runs, per network size : kernel serial vs kernel parallel across a core
# sweep, plus optionally a pyEDM serial baseline for the absolute kernel
# speedup. Reports wall time, parallel gain vs kernel-serial, and per-
# node-per-step cost. MUST run on multi-core hardware : on a single core
# the parallel column can only show overhead.
#
# Usage ( from repo root, kernel networks generated by make_test_network ):
#   python3 tests/scaling_eval.py --dir tests/scaling \
#           --sizes 200 500 1000 --cores 20 --pL 100 --baseline
#
# --baseline adds the pyEDM serial run ( slow ; omit for kernel-only ).

import argparse
import os
import subprocess
import time

#----------------------------------------------------------------------
def Run( net, data, backend, cores, kernel, pL, target = 'N0',
         E = 5, tau = -1, Tp = 1, chunks = None ):
    '''One RunNoConfig invocation ; returns wall seconds ( -1 on error ).'''

    cmd = [ 'python3', 'apps/RunNoConfig.py', '-md', 'generate',
            '-tn', target, '-nf', net, '-nd', data,
            '-pS', '500', '-pL', str( pL ),
            '-fn', 'Simplex', '-E', str( E ), '-tau', str( tau ),
            '-Tp', str( Tp ), '-c', str( cores ), '-b', backend,
            '-op', '/tmp/', '-do', 'scaling_tmp.csv' ]

    if kernel :
        cmd.append( '-K' )

    if chunks is not None :
        cmd += [ '-ch', str( chunks ) ]

    start = time.perf_counter()
    r     = subprocess.run( cmd, capture_output = True, text = True )
    wall  = time.perf_counter() - start

    if r.returncode != 0 :
        err = [ l for l in r.stderr.splitlines() if 'kedm' not in l ]
        print( '  ERROR :', '\n'.join( err[ -4: ] ) )
        return -1.0

    return wall

#----------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser( description = 'Kernel scaling eval' )
    parser.add_argument( '--dir', default = 'tests/scaling',
                         help = 'Directory of net_<N>.pkl / data_<N>.csv.' )
    parser.add_argument( '--sizes', nargs = '+', type = int,
                         default = [ 200, 500, 1000 ] )
    parser.add_argument( '--cores', type = int, default = 20,
                         help = 'Cores for the parallel run.' )
    parser.add_argument( '--pL', type = int, default = 100,
                         help = 'Generative steps.' )
    parser.add_argument( '--baseline', action = 'store_true',
                         help = 'Also time pyEDM serial ( slow ).' )
    parser.add_argument( '--E', type = int, default = 5,
                         help = 'Embedding dimension ( raises per-node '
                                'work ; try 5, 10, 20 ).' )
    parser.add_argument( '--chunks-sweep', action = 'store_true',
                         help = 'Sweep --chunks on the parallel run to test '
                                'whether coarser granularity recovers '
                                'par_gain.' )
    args = parser.parse_args()

    ncpu = os.cpu_count()
    print( f'host cpus = {ncpu} ; requested cores = {args.cores} ; '
           f'E = {args.E}' )

    if ncpu < 2 :
        print( 'WARNING : single-core host. The parallel column can only '
               'show overhead here ; run on multi-core hardware to '
               'measure node-level scaling.' )

    print()

    # Chunk-sweep mode : one size, vary --chunks on the parallel run to
    # isolate dispatch-granularity effects from per-node work.
    if args.chunks_sweep :
        size = args.sizes[ 0 ]
        net  = os.path.join( args.dir, f'net_{size}.pkl'  )
        data = os.path.join( args.dir, f'data_{size}.csv' )

        ks = Run( net, data, 'serial', ncpu, True, args.pL, E = args.E )
        print( f'{size} nodes, E={args.E} : kernel serial = {ks:.2f}s' )
        print( f'{"chunks":>8} {"kern_par":>9} {"par_gain":>8}' )

        for ch in ( args.cores, 2 * args.cores, 4 * args.cores,
                    8 * args.cores, size ) :
            kp   = Run( net, data, 'parallel', args.cores, True, args.pL,
                        E = args.E, chunks = ch )
            gain = ks / kp if kp > 0 else float( 'nan' )
            print( f'{ch:>8} {kp:>9.2f} {gain:>7.2f}x' )

        print()
        print( 'par_gain crossing 1.0 as chunks shrink => dispatch '
               'overhead was the limit ( coarser chunks win ). Flat below '
               '1.0 => per-node work too small ; batched kernel needed.' )
        return

    hdr = f'{"size":>6} {"kern_ser":>9} {"kern_par":>9} {"par_gain":>8} ' \
          f'{"us/node/step":>12}'
    if args.baseline :
        hdr = f'{"size":>6} {"pyEDM_ser":>10} ' + hdr[ 7: ] + \
              f' {"ker_speedup":>12}'
    print( hdr )

    for size in args.sizes :
        net  = os.path.join( args.dir, f'net_{size}.pkl'  )
        data = os.path.join( args.dir, f'data_{size}.csv' )

        if not os.path.exists( net ) :
            print( f'{size:>6}  MISSING {net}' )
            continue

        ks = Run( net, data, 'serial',   ncpu,       True,  args.pL,
                  E = args.E )
        kp = Run( net, data, 'parallel', args.cores, True,  args.pL,
                  E = args.E )

        gain = ks / kp if kp > 0 else float( 'nan' )
        per  = ks / ( size * args.pL ) * 1e6 if ks > 0 else float( 'nan' )

        if args.baseline :
            tp  = Run( net, data, 'serial', 4, False, args.pL, E = args.E )
            spd = tp / ks if ks > 0 else float( 'nan' )
            print( f'{size:>6} {tp:>10.2f} {ks:>9.2f} {kp:>9.2f} '
                   f'{gain:>7.2f}x {per:>12.1f} {spd:>11.1f}x' )
        else :
            print( f'{size:>6} {ks:>9.2f} {kp:>9.2f} {gain:>7.2f}x '
                   f'{per:>12.1f}' )

    print()
    print( 'par_gain > 1 => kernel unlocked node parallelism the pyEDM '
           'path could not ( T4 ). ker_speedup = pyEDM_serial / '
           'kernel_serial ( the envelope-deletion win ).' )

#----------------------------------------------------------------------
if __name__ == '__main__':
    main()
